export function makeT(lang) {
  const table = STR[lang] || STR.en;
  return (key, vars) => {
    let s = table[key] ?? STR.en[key] ?? key;
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, v);
    return s;
  };
}
